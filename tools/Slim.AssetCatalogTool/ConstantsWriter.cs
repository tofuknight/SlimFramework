using System.Globalization;
using System.Text;

namespace SlimFramework.Tools.AssetCatalogTool;

/// <summary>写出 DisplayKey → ref_key 的常量类。换行固定为 LF，编码由调用方写成无 BOM 的 UTF-8。</summary>
internal static class ConstantsWriter
{
    public static string Write(IReadOnlyList<AssetManifestEntry> entries, string namespaceName, string className)
    {
        var named = entries.Where(static entry => entry.Constant.Length > 0).OrderBy(static entry => entry.RefKey).ToList();
        var unnamed = entries.Count - named.Count;
        var builder = new StringBuilder();
        builder.Append("// <auto-generated>\n");
        builder.Append("// 由 Slim.AssetCatalogTool 生成。不要手改。\n");
        builder.Append("// ref_key 是运行时和存档身份。本类把 DisplayKey 映射到 ref_key。\n");
        builder.Append("// 玩法代码使用这些常量，不要写 res:// 路径或手写 ref_key。\n");
        if (unnamed > 0)
        {
            builder.Append("// 另有 ");
            builder.Append(unnamed.ToString(CultureInfo.InvariantCulture));
            builder.Append(" 条 constant 为空，不在本类中，只能按 ref_key 取。\n");
        }

        builder.Append('\n');
        builder.Append("namespace ").Append(namespaceName).Append(";\n");
        builder.Append('\n');
        builder.Append("public static class ").Append(className).Append('\n');
        builder.Append("{\n");
        for (var i = 0; i < named.Count; i++)
        {
            if (i > 0)
                builder.Append('\n');
            var entry = named[i];
            builder.Append("    /// <summary>");
            builder.Append(XmlText(Describe(entry)));
            builder.Append("</summary>\n");
            builder.Append("    public const int ");
            builder.Append(entry.Constant);
            builder.Append(" = ");
            builder.Append(entry.RefKey.ToString(CultureInfo.InvariantCulture));
            builder.Append(";\n");
        }

        builder.Append("}\n");
        return builder.ToString();
    }

    private static string Describe(AssetManifestEntry entry)
    {
        var hasPath = entry.Path.Length > 0;
        var hasUid = entry.Uid.Length > 0;
        if (hasPath && hasUid)
            return entry.Path + " " + entry.Uid;
        return hasPath ? entry.Path : entry.Uid;
    }

    private static string XmlText(string text) =>
        text.Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal);
}
